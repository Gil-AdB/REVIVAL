struct StaticShadowLightmap;  // FDS/Base/StaticShadowLightmap.h
struct VertexFrame;           // FDS/Base/VertexFrame.h

#pragma pack(push, 1)

// [172 Bytes]
// Total: [220 Bytes + 84 Bytes per Vertex + 56 Bytes per Face +
//         16 Bytes * (Spline Keys + Hide Keys)]
struct TriMesh
{
    // strided array containing precalculated lighting.
    // uses packed dword BGRA to reduce memory read bandwidth usage
    // was optimized out for sse benefit
    Color			*SL             = nullptr;
    DWord            VIndex         = 0;     //Amount of Vertices on Mesh
    DWord            FIndex         = 0;     //Amount of Faces on Mesh
    DWord            EIndex         = 0;     //Amount of Edges on Mesh
    Vertex         * Verts          = nullptr;      //Vertex List
    Face           * Faces          = nullptr;      //Face List
    Edge           * Edges          = nullptr;      //Edge List
    Spline           Pos;        //Position Track Spline
    Spline           Scale;      //Scale Track Spline
    Spline           Rotate;     //Orientation Track Spline
    ObjectStatus   * Status         = nullptr;     //Hide Track (crap)
    ObjectStatus   * CurStat        = nullptr;    //Current Hide status
    Vector           IPos;       //Interpolated Position
    Vector           IScale;     //Interpolated Scale
    Quaternion       IRot;       //Interpolated Orientation (Quaternion)
    Matrix           UnscaledRotMat = { 0 };     // So yeah
    Matrix           RotMat         = { 0 };     //Interpolated Orientation (Matrix)
    Vector		     Heading;    // Generated by Position Track spline for meshes with the Align to path flag.
    Vector           BSphereCtr; // Bounding Sphere Center.
    Vector           BSphereScreenPos; // Bounding Sphere Center.
    float			 BSphereRadius  = 0.0f; // Bounding Sphere Radius.
    float            BSphereRad     = 0.0f; // Bounding Sphere Radius, squared. kept for backward compatibility until pipeline code is updated
    DWord            Flags          = 0;

    // env_cube (forward reflective path): six PARABOLOID hemisphere sheets
    // (Sachletz-tiled, pow2), one per axis direction, synthesized at init
    // from the padded cube-face bake. Transform's Face_Reflective block
    // binds each triangle to the sheet of its PANEL NORMAL's dominant axis
    // — static for static geometry, so the chart never changes with the
    // camera (the camera-dependent cube-face pick + wide-span fallback both
    // popped as charts flipped while moving). Null (default) → the legacy
    // equirect F->ReflectionTexture path runs unchanged. See RENDER/EnvCube.h.
    Texture         *EnvHemiSheets[6] = { nullptr, nullptr, nullptr,
                                          nullptr, nullptr, nullptr };

    // --env_live_water: this mesh's probe bake's per-texel WATER VERDICT,
    // 1 bit per texel at the bake's full face resolution (6 x
    // EnvWaterMaskRes²/8 bytes, face-major, EnvCube face order — the layout
    // fds::EnvLiveWater_MaskBit indexes). The forward reflective path reads it
    // per CORNER here (for the per-face tilt amplitude) and per PIXEL in the
    // filler (via the sheets' alpha byte, which carries the same bit), so only
    // the reflected water moves, not the reflected skyline. Non-owning: the
    // scene that baked the faces owns the storage for the scene's lifetime
    // (CITY). Null → no tilt (see fds::EnvLiveWater_PerturbDir).
    const uint8_t   *EnvWaterMask    = nullptr;
    int              EnvWaterMaskRes = 0;

    // Per-shadow-bake-call cache. Written SERIALLY by Render_Deferred-
    // ShadowMaps' prime pass before it enqueues the parallel per-face
    // Transform_Objects tasks; the tasks read it only (valid when
    // BakeCacheGen == g_shadowBakeGen). Replaces a per-mesh-per-face
    // spline-extent walk (isDynamicForBake) and world-bsphere
    // MatrixXVector, which are identical across all 6 cube faces of
    // every light in the call.
    Vector           BakeWsBSphereCtr;
    uint32_t         BakeCacheGen   = 0;
    uint8_t          BakeIsDynamic  = 0;

    // Pre-baked per-face shadow factor for static omnis. Allocated by
    // LightmapBake_Static at scene init when --shadow-lightmap is on
    // and this mesh is "effectively static" (Pos/Rotate splines have
    // extent < threshold or NumKeys <= 1). nullptr → mesh runs the
    // legacy per-pixel cube-shadow tap path. See StaticShadowLightmap.h.
    StaticShadowLightmap *staticShadowLM = nullptr;

    // Index into Scene::staticLMTable. 0 = no lightmap (default). 1..N
    // = position of this mesh's lightmap pointer in the scene table.
    // Set by LightmapBake_Static; written by Mekalele into the G-buffer
    // per-pixel so the deferred kernel can look up the lightmap.
    uint16_t         staticLMMeshId = 0;

    // Optional pre-computed world-space vertex positions, aligned with
    // Verts[0..VIndex-1]. When non-null AND the mesh is static (Animate_
    // Objects skips it, e.g. via Tri_Possessed), the cube-face shadow
    // xform can:
    //   1. Per-vertex pyramid cull in world space (one dot product + a
    //      few compares; no matmul). Outside-vertices skip the view xform.
    //   2. Inside-vertices: view-space TPos_AOS = view.Mat × (worldPos - cam.ISource).
    //      Same number of mul/add as the legacy M34 × Vtx->Pos path, but
    //      without the per-face object→world step baked into M.
    // Allocated by scene init for static chunks (e.g. greets's split
    // Piramid). Other meshes leave this null; xform falls back to the
    // legacy per-face matrix path.
    Vector         * worldVerts    = nullptr;

    // SoA refactor (Phase 1+ — see docs/SOA_VERTEX_REFACTOR.md). Per-
    // frame writable transformed-vertex state as SoA arrays. nullptr
    // until Transform_Objects first touches the mesh (lazy-alloc via
    // ensureSized). Phase 1 dual-writes (AoS + SoA); Phase 2 switches
    // Transform to wide-SIMD writing only SoA; Phases 4-5 migrate
    // consumers off the AoS Vertex transformed fields.
    VertexFrame     *frame              = nullptr;

    // Editor per-object uniform scale multiplier (browser editor scale knob /
    // 'obj:<name>|scale|v' sidecar lines — see DEMO/MaterialImport.h). Same
    // 0-sentinel convention as Omni::FlareScale: 0 = unset → authored 1.0,
    // so the many memset(0) TriMesh creation sites (FLD convert, mirror
    // clones, chunk splits) keep their look byte-identically. >0 multiplies
    // the Scale-spline result in Animate_Objects — the scale pivots on the
    // object pivot and composes down the parent→child matrix chain exactly
    // like authored scale. Static (Tri_Possessed) meshes never re-run
    // Animate_Objects, so the knob cannot affect them (greets' baked room).
    float            EditorScale        = 0.0f;

    // World-space axis-aligned bounding box (Foundation F, docs/
    // ENVDYN_DISPLACEMENT_PLAN.md). Maintained by WorldAabb_UpdateScene:
    // LocalAabb* is the model-space box, computed ONCE from Verts;
    // WorldAabb* is the posed box. Static meshes compute the world box
    // once (post first transform); dynamic meshes (isDynamicForBake)
    // recompute it each frame by transforming the eight LocalAabb corners
    // through RotMat + IPos (conservative under rotation). Consumed by the
    // frustum-vs-AABB reject (main camera / probe face pyramid) and the
    // --draw_aabbs overlay. Zero-init (memset TriMesh sites) leaves both
    // Valid flags 0 = "not yet computed"; no effect until F/A code reads it.
    Vector           LocalAabbMin, LocalAabbMax;
    Vector           WorldAabbMin, WorldAabbMax;
    uint8_t          LocalAabbValid = 0;   // model-space box computed
    uint8_t          WorldAabbValid = 0;   // world box valid (static: once)

    // this is a temporary hack and will be removed in the future
    dword			 SortPriorityBias   = 0; // '1' value causes object to always be rendered first

    // Per-frame "seen this mesh in the deferred transparent peel order"
    // stamp. Compared against a frame counter to dedup TriMesh* entries
    // when building the per-object peel list from FList. Stale leftover
    // value across frames is fine — counter increments each frame, so
    // never collides.
    uint32_t         XparSeenFrame      = 0;

    TriMesh      * Next             = nullptr;
    TriMesh      * Prev             = nullptr;

#if FDS_VIS_CENSUS
    // DIAGNOSTIC ONLY (--xfrm_ablate bit 2048). A compact, SHARED, 12 B/vert
    // copy of this mesh's object-space Pos, so the shadow pass's per-vertex
    // loop can be re-timed reading it instead of reading Pos out of its
    // per-light 140-byte clone Vertex. Built once per mesh, never written
    // again. Absent from the shipping build.
    std::atomic<float*> DiagPos { nullptr };
#endif
};

#pragma pack(pop)

#endif //REVIVAL_TRIMESH_H
